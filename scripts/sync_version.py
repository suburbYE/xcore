"""One version, written everywhere from a single file.

The repository carried five version literals and three of them were wrong:

    src/main.cpp:165    XCORE_VERSION = "0.31.0"   (called itself the source of truth)
    src/main.cpp:984    out["version"] = "0.18.0"  (machine-readable, AI parses this)
    src/xcore.cpp:719   "X-Core v0.22.0"           (usage banner)
    src/xcore.cpp:733   out["version"] = "0.5"     (machine-readable, AI parses this)
    build.bat:1         "-- unified binary v0.22.0"

Two of those are in `--json` output, so a script reading the binary was told the
tool was version 0.18.0 or 0.5 while `xcore --version` said 0.31.0 and the
documents said 0.39.0. Four answers to one question is not a version number;
it is a way to make a build unreproducible.

`VERSION` is now the only place a human edits. This script projects it.

Run:  python scripts/sync_version.py [--check]
      --check exits non-zero if anything is out of step (for CI / tests)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = ROOT / "VERSION"

# Target name -> the file this script is allowed to rewrite.
GENERATED_HEADER = ROOT / "src" / "version.h"
CLIENT_PKG = ROOT / "client" / "package.json"
TAURI_CONF = ROOT / "client" / "src-tauri" / "tauri.conf.json"
CARGO_TOML = ROOT / "client" / "src-tauri" / "Cargo.toml"
README = ROOT / "README.md"
HANDOVER = ROOT / "HANDOVER.md"

# The documents count. The five-literal drift this script exists for was found
# by noticing that README said v0.39.0 while the binary said 0.31.0, so leaving
# the docs out of the check would leave the original symptom unguarded.
DOC_PATTERNS: tuple[tuple[Path, str, str], ...] = (
    (README, r"^# X-Core v(\d+\.\d+\.\d+)$",
     "# X-Core v{version}"),
    (HANDOVER, r"> 项目版本：\*\*v(\d+\.\d+\.\d+)\*\*",
     "> 项目版本：**v{version}**"),
)

HEADER_BODY = """// GENERATED by scripts/sync_version.py from the VERSION file -- do not edit.
//
// One definition, included everywhere, so the version in `--json` output cannot
// disagree with the version in the banner or with the documents. Three stale
// literals had accumulated before this existed; two of them were in JSON that
// scripts parse.
#pragma once

#define XCORE_VERSION "{version}"
"""


def read_version() -> str:
    raw = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+", raw):
        raise SystemExit(
            f"VERSION must be a bare semver like 1.0.0, got {raw!r}")
    return raw


def current_versions() -> dict[str, str | None]:
    """What each target currently claims, for --check and for reporting."""
    out: dict[str, str | None] = {}

    if GENERATED_HEADER.exists():
        m = re.search(r'#define XCORE_VERSION "([^"]+)"',
                      GENERATED_HEADER.read_text(encoding="utf-8"))
        out["src/version.h"] = m.group(1) if m else None
    else:
        out["src/version.h"] = None

    for label, path, key in (
        ("client/package.json", CLIENT_PKG, "version"),
        ("client/src-tauri/tauri.conf.json", TAURI_CONF, "version"),
    ):
        try:
            out[label] = json.loads(path.read_text(encoding="utf-8")).get(key)
        except Exception:
            out[label] = None

    try:
        m = re.search(r'^version\s*=\s*"([^"]+)"',
                      CARGO_TOML.read_text(encoding="utf-8"), re.M)
        out["client/src-tauri/Cargo.toml"] = m.group(1) if m else None
    except Exception:
        out["client/src-tauri/Cargo.toml"] = None

    for path, pattern, _ in DOC_PATTERNS:
        label = str(path.relative_to(ROOT))
        try:
            m = re.search(pattern, path.read_text(encoding="utf-8"), re.M)
            out[label] = m.group(1) if m else None
        except Exception:
            out[label] = None

    return out


def stale_literals() -> list[tuple[str, int, str]]:
    """Version-looking literals still hardcoded in the C++ sources.

    `version.h` is excluded: it is the generated file, and flagging it would
    make the check always fail.
    """
    hits: list[tuple[str, int, str]] = []
    pattern = re.compile(r'"(\d+\.\d+(?:\.\d+)?)"')
    for src in sorted((ROOT / "src").glob("*.cpp")) + sorted((ROOT / "tools").glob("*.cpp")):
        for i, line in enumerate(src.read_text(encoding="utf-8",
                                              errors="replace").splitlines(), 1):
            if "version" not in line.lower():
                continue
            for m in pattern.finditer(line):
                hits.append((str(src.relative_to(ROOT)), i, m.group(1)))
    return hits


def write_version(version: str) -> None:
    GENERATED_HEADER.parent.mkdir(parents=True, exist_ok=True)
    GENERATED_HEADER.write_text(HEADER_BODY.format(version=version),
                                encoding="utf-8")

    pkg = json.loads(CLIENT_PKG.read_text(encoding="utf-8"))
    pkg["version"] = version
    CLIENT_PKG.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8")

    conf = json.loads(TAURI_CONF.read_text(encoding="utf-8"))
    conf["version"] = version
    TAURI_CONF.write_text(json.dumps(conf, indent=2) + "\n", encoding="utf-8")

    toml = CARGO_TOML.read_text(encoding="utf-8")
    toml = re.sub(r'^version\s*=\s*"[^"]+"', f'version = "{version}"',
                  toml, count=1, flags=re.M)
    CARGO_TOML.write_text(toml, encoding="utf-8")

    for path, pattern, replacement in DOC_PATTERNS:
        text = path.read_text(encoding="utf-8")
        new_text, n = re.subn(pattern, replacement.format(version=version),
                              text, count=1, flags=re.M)
        if n:
            path.write_text(new_text, encoding="utf-8")
        else:
            print(f"  [warn] {path.name}: version line not found; not updated")


def main() -> int:
    check_only = "--check" in sys.argv
    version = read_version()
    print(f"VERSION = {version}")

    if check_only:
        bad = {k: v for k, v in current_versions().items() if v != version}
        stale = stale_literals()
        for label, got in current_versions().items():
            mark = "ok  " if got == version else "STALE"
            print(f"  [{mark}] {label}: {got}")
        for path, line, lit in stale:
            print(f"  [STALE] {path}:{line} hardcodes {lit!r}")
        if bad or stale:
            print(f"\n{len(bad)} file(s) and {len(stale)} literal(s) out of step")
            return 1
        print("\nall targets agree")
        return 0

    write_version(version)
    for label, got in current_versions().items():
        mark = "ok" if got == version else "FAILED"
        print(f"  [{mark}] {label} -> {got}")

    stale = stale_literals()
    if stale:
        print("\nstill hardcoded in C++ (fix by hand; this script will not "
              "guess at source):")
        for path, line, lit in stale:
            print(f"  {path}:{line}  {lit!r}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
