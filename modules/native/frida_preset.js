/**
 * frida_preset.js — Frida 脚本模板生成器
 *
 * 根据壳类型生成对应的 Frida DEX dump 脚本。
 * 所有模板使用 ES5 语法以兼容旧版 Frida。
 *
 * 用法：
 *   const fp = require('./frida_preset');
 *   const script = fp.generate({ shellName: '360加固', packageName: 'com.example.app' });
 */

const path = require('path');

/**
 * 生成 Frida dump 脚本
 * @param {object} opts
 * @param {string} opts.shellName - 壳名称
 * @param {string} opts.packageName - APK 包名
 * @param {string} opts.outputDir - 输出目录
 * @returns {{ script: string, path: string, spawnCmd: string, attachCmd: string }}
 */
function generate(opts) {
    const shellName = opts.shellName || 'unknown';
    const pkg = opts.packageName || 'com.example.app';
    const outputDir = opts.outputDir || 'output';

    const safeName = shellName.replace(/[^a-zA-Z0-9\u4e00-\u9fff_-]/g, '_');
    const fileName = 'frida_' + pkg.replace(/\./g, '_') + '_' + safeName + '.js';
    const filePath = path.join(outputDir, fileName);

    const script = buildTemplate(shellName, pkg);

    return {
        script: script,
        path: filePath,
        fileName: fileName,
        spawnCmd: 'frida -U -f ' + pkg + ' -l ' + fileName + ' --no-pause',
        attachCmd: 'frida -U ' + pkg + ' -l ' + fileName
    };
}

/**
 * 构建 Frida 脚本模板
 */
function buildTemplate(shellName, packageName) {
    var header = (
        '/**\n' +
        ' * Frida DEX Dump Script\n' +
        ' * Generated by xcore native shell classifier\n' +
        ' * Shell: ' + shellName + '\n' +
        ' * Target: ' + packageName + '\n' +
        ' *\n' +
        ' * Usage:\n' +
        ' *   Spawn mode (recommended):\n' +
        ' *     frida -U -f ' + packageName + ' -l this_script.js --no-pause\n' +
        ' *   Attach mode:\n' +
        ' *     frida -U ' + packageName + ' -l this_script.js\n' +
        ' *\n' +
        ' * Anti-detection notes:\n' +
        ' *   - Some shells detect frida-server by port scanning (default 27042).\n' +
        ' *     Use: frida-server -l 0.0.0.0:1234   then   frida -H 127.0.0.1:1234\n' +
        ' *   - Some shells check /proc/self/maps for "frida" or "gum-js".\n' +
        ' *     Use frida-gadget injection or rename frida-server binary.\n' +
        ' *   - VMP shells may use custom libart.so/libdvm.so replacements.\n' +
        ' *     The hooks below target standard ART symbols; adjust if needed.\n' +
        ' */\n\n'
    );

    var common = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Common utilities\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'var DEX_MAGIC = [0x64, 0x65, 0x78, 0x0a]; // "dex\\n"\n\n' +
        'function writeDex(fileName, data) {\n' +
        '    var file = new File("/data/local/tmp/" + fileName, "wb");\n' +
        '    file.write(data);\n' +
        '    file.close();\n' +
        '    console.log("[+] Dumped: /data/local/tmp/" + fileName);\n' +
        '}\n\n' +
        'function isDexData(buffer) {\n' +
        '    if (!buffer || buffer.byteLength < 8) return false;\n' +
        '    var bytes = new Uint8Array(buffer);\n' +
        '    for (var i = 0; i < DEX_MAGIC.length; i++) {\n' +
        '        if (bytes[i] !== DEX_MAGIC[i]) return false;\n' +
        '    }\n' +
        '    return true;\n' +
        '}\n\n' +
        'function dumpMemory(addr, size, name) {\n' +
        '    try {\n' +
        '        var data = Memory.readByteArray(addr, size);\n' +
        '        if (isDexData(data)) {\n' +
        '            writeDex(name + ".dex", data);\n' +
        '        } else {\n' +
        '            console.log("[-] Not valid DEX at " + addr + " (size=" + size + ")");\n' +
        '        }\n' +
        '    } catch (e) {\n' +
        '        console.log("[-] dumpMemory error: " + e.message);\n' +
        '    }\n' +
        '}\n\n'
    );

    var jniHook = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Hook 1: JNI RegisterNatives\n' +
        '// Purpose: Capture dynamically registered native methods.\n' +
        '// Many shelling solutions use RegisterNatives instead of\n' +
        '// static JNI binding (Java_com_xxx_ method naming).\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'var RegisterNatives = Module.findExportByName("libart.so", "RegisterNatives") ||\n' +
        '                      Module.findExportByName("libart.so", "_ZN3art3JNI15RegisterNativesEP7_JNIEnvP7_jclassPK15JNINativeMethodi");\n\n' +
        'if (RegisterNatives) {\n' +
        '    var RegisterNativesPtr = new NativeFunction(RegisterNatives, "int", ["pointer", "pointer", "pointer", "int"]);\n' +
        '    Interceptor.attach(RegisterNatives, {\n' +
        '        onEnter: function(args) {\n' +
        '            var env = args[0];\n' +
        '            var clazz = args[1];\n' +
        '            var methods = args[2];\n' +
        '            var count = args[3].toInt32();\n' +
        '            var className = Java.vm.tryGetEnv().getClassName(clazz);\n' +
        '            console.log("[RegisterNatives] class=" + className + " count=" + count);\n' +
        '            this.className = className;\n' +
        '        },\n' +
        '        onLeave: function(retval) {\n' +
        '            // No action needed on leave for RegisterNatives\n' +
        '        }\n' +
        '    });\n' +
        '    console.log("[+] Hooked: RegisterNatives");\n' +
        '} else {\n' +
        '    console.log("[-] RegisterNatives not found in libart.so");\n' +
        '}\n\n'
    );

    var dexClassLoaderHook = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Hook 2: DexClassLoader / BaseDexClassLoader constructor\n' +
        '// Purpose: Capture DEX file paths passed to the class loader.\n' +
        '// Many light shells decrypt DEX to a temp path and load it here.\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'Java.perform(function() {\n' +
        '    try {\n' +
        '        var DexClassLoader = Java.use("dalvik.system.DexClassLoader");\n' +
        '        DexClassLoader.$init.overload("java.lang.String", "java.lang.String", "java.lang.String", "java.lang.ClassLoader").implementation = function(dexPath, optDir, libPath, parent) {\n' +
        '            console.log("[DexClassLoader] dexPath=" + dexPath + " optDir=" + optDir);\n' +
        '            // Try to read and dump the DEX file\n' +
        '            try {\n' +
        '                var file = Java.use("java.io.File").$new(dexPath);\n' +
        '                if (file.exists()) {\n' +
        '                    var stream = Java.use("java.io.FileInputStream").$new(file);\n' +
        '                    var bytes = Java.array("byte", new Array(file.length()).fill(0));\n' +
        '                    stream.read(bytes);\n' +
        '                    stream.close();\n' +
        '                    if (isDexData(bytes)) {\n' +
        '                        writeDex("classloader_" + Date.now() + ".dex", bytes);\n' +
        '                    }\n' +
        '                }\n' +
        '            } catch (e2) {\n' +
        '                console.log("[-] DexClassLoader read error: " + e2);\n' +
        '            }\n' +
        '            return this.$init(dexPath, optDir, libPath, parent);\n' +
        '        };\n' +
        '        console.log("[+] Hooked: DexClassLoader.$init");\n' +
        '    } catch (e) {\n' +
        '        console.log("[-] DexClassLoader hook failed: " + e);\n' +
        '    }\n' +
        '});\n\n'
    );

    var openDexHook = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Hook 3: DexFile / openDexFile (ART internal)\n' +
        '// Purpose: Catch the moment ART opens a DEX file from memory/disk.\n' +
        '// This is the most reliable hook point for heavy shells because\n' +
        '// the DEX must be in memory when ART loads it.\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'var openDexFileNative = Module.findExportByName("libart.so", "OpenDexFilesFromOat") ||\n' +
        '                        Module.findExportByName("libart.so", "_ZN3art7DexFile10OpenMemoryEPKhmRKNSt3__112basic_stringIcNS3_11char_traitsIcEENS3_9allocatorIcEEEEjPNS_11MemMapEmCacheE");\n\n' +
        'if (openDexFileNative) {\n' +
        '    Interceptor.attach(openDexFileNative, {\n' +
        '        onEnter: function(args) {\n' +
        '            // args[0] = dex buffer pointer, args[1] = size\n' +
        '            var size = args[1].toInt32();\n' +
        '            if (size > 0 && size < 100 * 1024 * 1024) {\n' +
        '                var addr = args[0];\n' +
        '                var name = "opendex_" + Date.now() + "_" + size;\n' +
        '                dumpMemory(addr, size, name);\n' +
        '            }\n' +
        '            this.size = size;\n' +
        '        },\n' +
        '        onLeave: function(retval) {\n' +
        '            // retval typically holds the DexFile pointer\n' +
        '        }\n' +
        '    });\n' +
        '    console.log("[+] Hooked: OpenDexFilesFromOat");\n' +
        '} else {\n' +
        '    // Try alternative: DexFile::OpenMemory\n' +
        '    var openMemory = Module.findExportByName("libart.so", "_ZN3art7DexFile10OpenMemoryEPKhmRKNSt3__112basic_stringIcNS3_11char_traitsIcEENS3_9allocatorIcEEEEjPNS_11MemMapEmCacheE");\n' +
        '    if (openMemory) {\n' +
        '        Interceptor.attach(openMemory, {\n' +
        '            onEnter: function(args) {\n' +
        '                var size = args[1].toInt32();\n' +
        '                if (size > 0 && size < 100 * 1024 * 1024) {\n' +
        '                    dumpMemory(args[0], size, "openmemory_" + Date.now() + "_" + size);\n' +
        '                }\n' +
        '            }\n' +
        '        });\n' +
        '        console.log("[+] Hooked: DexFile::OpenMemory");\n' +
        '    } else {\n' +
        '        console.log("[-] No openDexFile hook point found");\n' +
        '    }\n' +
        '}\n\n'
    );

    var loadMethodHook = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Hook 4: ClassLinker::LoadMethod (ART internal)\n' +
        '// Purpose: Monitor method loading during class initialization.\n' +
        '// Useful for VMP detection: if LoadMethod is called for custom\n' +
        '// interpreted methods rather than native-compiled ones.\n' +
        '// NOTE: May cause significant performance overhead on large apps.\n' +
        '// Comment out if the app becomes unresponsive.\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'var LoadMethod = Module.findExportByName("libart.so", "_ZN3art11ClassLinker10LoadMethodERKNS_7DexFileERKNS_8ClassDataENS_6HandleINS_6mirror10ExecutableEEE") ||\n' +
        '                  Module.findExportByName("libart.so", "_ZN3art11ClassLinker10LoadMethodERKNS_7DexFileERKNS_8ClassDataENS_6HandleINS_6mirror5ClassEEE");\n\n' +
        'if (LoadMethod) {\n' +
        '    var loadCount = 0;\n' +
        '    Interceptor.attach(LoadMethod, {\n' +
        '        onEnter: function(args) {\n' +
        '            loadCount++;\n' +
        '            if (loadCount % 100 === 0) {\n' +
        '                console.log("[LoadMethod] loaded " + loadCount + " methods so far");\n' +
        '            }\n' +
        '        }\n' +
        '    });\n' +
        '    console.log("[+] Hooked: ClassLinker::LoadMethod");\n' +
        '} else {\n' +
        '    console.log("[-] LoadMethod not found (may be inlined on newer ART)");\n' +
        '}\n\n'
    );

    var vmDetection = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// VMP Detection Helpers\n' +
        '// Purpose: Check for VMP-specific runtime indicators.\n' +
        '// VMP shells replace or modify libart.so / libdvm.so.\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'function detectVMP() {\n' +
        '    var modules = Process.enumerateModules();\n' +
        '    for (var i = 0; i < modules.length; i++) {\n' +
        '        var name = modules[i].name;\n' +
        '        if (name.indexOf("libdvm") !== -1 || name.indexOf("libvmpshield") !== -1 ||\n' +
        '            name.indexOf("libexec") !== -1 || name.indexOf("libavmp") !== -1) {\n' +
        '            console.log("[VMP] Detected VMP-related module: " + name + " at " + modules[i].base);\n' +
        '        }\n' +
        '    }\n' +
        '}\n' +
        'detectVMP();\n\n'
    );

    var summary = (
        '// ═══════════════════════════════════════════════════════════════\n' +
        '// Summary & Next Steps\n' +
        '// ═══════════════════════════════════════════════════════════════\n\n' +
        'console.log("\\n===========================================");\n' +
        'console.log(" Frida DEX Dump Script Active");\n' +
        'console.log(" Shell: ' + shellName + '");\n' +
        'console.log(" Target: ' + packageName + '");\n' +
        'console.log("===========================================");\n' +
        'console.log("Dumped DEX files will appear in /data/local/tmp/");\n' +
        'console.log("After the app runs, pull them with:");\n' +
        'console.log("  adb pull /data/local/tmp/ .");\n' +
        'console.log("===========================================\\n");\n'
    );

    return header + common + jniHook + dexClassLoaderHook + openDexHook + loadMethodHook + vmDetection + summary;
}

/**
 * generateSpawnPreset — Phase 4c: Spawn-mode Frida script fragment
 *
 * Generates a Frida script fragment for early-attach (spawn) scenarios.
 * Includes: android_dlopen_ext hook, Process.setExceptionHandler, auto-resume,
 * delay loop until target library loads, then install all hooks.
 *
 * @param {string} libName - Target .so name (e.g. "libsscronet.so")
 * @param {Array} keyRVAs - Array of {label, rva, size, trigger} probe configs
 * @param {Array} cryptoFuncs - Array of {name, log_args} crypto function hooks
 * @returns {string} Frida script fragment (ES5)
 */
function generateSpawnPreset(libName, keyRVAs, cryptoFuncs) {
    var rvas = keyRVAs || [];
    var cryptos = cryptoFuncs || [];

    var script = '';

    // ── Crash handler ──
    script += (
        '// ═══ Spawn Preset: Crash Handler ═══\n' +
        'Process.setExceptionHandler(function(details) {\n' +
        '    console.log("[!] Exception: " + details.type + " at " + details.address +\n' +
        '                " context=" + JSON.stringify(details.context));\n' +
        '    return false;\n' +
        '});\n' +
        'console.log("[*] Crash handler installed");\n\n'
    );

    // ── Early dlopen/android_dlopen_ext hook ──
    script += (
        '// ═══ Spawn Preset: Early .so Load Hook ═══\n' +
        'var targetLib = "' + libName + '";\n' +
        'var hooksInstalled = false;\n' +
        'var waitCheckCount = 0;\n' +
        '\n' +
        'var android_dlopen_ext = Module.findExportByName(null, "android_dlopen_ext");\n' +
        'if (android_dlopen_ext) {\n' +
        '    Interceptor.attach(android_dlopen_ext, {\n' +
        '        onEnter: function(args) {\n' +
        '            this.path = args[0] ? args[0].readCString() : "";\n' +
        '        },\n' +
        '        onLeave: function(retval) {\n' +
        '            if (this.path && this.path.indexOf(targetLib) !== -1) {\n' +
        '                console.log("[android_dlopen_ext] " + this.path + " loaded");\n' +
        '                if (!hooksInstalled) {\n' +
        '                    hooksInstalled = true;\n' +
        '                    setTimeout(installAllHooks, 50);\n' +
        '                }\n' +
        '            }\n' +
        '        }\n' +
        '    });\n' +
        '    console.log("[*] android_dlopen_ext hook installed (waiting for " + libName + ")");\n' +
        '} else {\n' +
        '    console.log("[!] android_dlopen_ext not found, using periodic check");\n' +
        '}\n\n'
    );

    // ── Periodic module check ──
    script += (
        '// ═══ Spawn Preset: Periodic Module Check ═══\n' +
        'function waitForLibrary() {\n' +
        '    var mod = Process.findModuleByName(targetLib);\n' +
        '    if (mod && !hooksInstalled) {\n' +
        '        hooksInstalled = true;\n' +
        '        installAllHooks();\n' +
        '        return;\n' +
        '    }\n' +
        '    waitCheckCount++;\n' +
        '    if (waitCheckCount % 20 === 0) {\n' +
        '        console.log("[*] Still waiting for " + targetLib + " (" + waitCheckCount + " checks)");\n' +
        '    }\n' +
        '    if (waitCheckCount < 600) { // max ~30 seconds\n' +
        '        setTimeout(waitForLibrary, 50);\n' +
        '    } else {\n' +
        '        console.log("[!] Timeout waiting for " + targetLib);\n' +
        '    }\n' +
        '}\n\n'
    );

    // ── Dump helper ──
    script += (
        '// ═══ Spawn Preset: Hex Dump Helper ═══\n' +
        'function dumpHex(label, addr, size) {\n' +
        '    console.log("════ HEXDUMP [" + label + "] @ " + addr + " ═══");\n' +
        '    try {\n' +
        '        var bytes = addr.readByteArray(size);\n' +
        '        if (bytes) {\n' +
        '            console.log(hexdump(bytes, { offset: 0, length: size, header: true, ansi: false }));\n' +
        '        }\n' +
        '    } catch (e) {\n' +
        '        console.log("  dumpHex error: " + e.message);\n' +
        '    }\n' +
        '}\n\n'
    );

    // ── RVA hooks ──
    if (rvas.length > 0) {
        script += (
            '// ═══ Spawn Preset: RVA Hooks ═══\n' +
            'var rvaProbes = [\n'
        );
        for (var i = 0; i < rvas.length; i++) {
            var p = rvas[i];
            script += (
                '    { label: "' + (p.label || "probe" + i) + '", rva: ' + (p.rva || 0) +
                ', size: ' + (p.size || 64) + ', trigger: "' + (p.trigger || "call_on_enter") + '" }'
            );
            if (i < rvas.length - 1) script += ',';
            script += '\n';
        }
        script += '];\n\n';

        script += (
            'function installRVAHooks(mod) {\n' +
            '    console.log("[*] Installing " + rvaProbes.length + " RVA hooks on " + targetLib);\n' +
            '    for (var i = 0; i < rvaProbes.length; i++) {\n' +
            '        var p = rvaProbes[i];\n' +
            '        var addr = mod.base.add(p.rva);\n' +
            '        if (p.trigger === "immediate") {\n' +
            '            dumpHex(p.label, addr, p.size);\n' +
            '        } else if (p.trigger === "call_on_enter") {\n' +
            '            (function(probe, probeAddr) {\n' +
            '                Interceptor.attach(probeAddr, {\n' +
            '                    onEnter: function(args) {\n' +
            '                        dumpHex(probe.label, probeAddr, probe.size);\n' +
            '                    }\n' +
            '                });\n' +
            '            })(p, addr);\n' +
            '            console.log("  [+] " + p.label + " @ " + addr);\n' +
            '        } else if (p.trigger === "call_on_leave") {\n' +
            '            (function(probe, probeAddr) {\n' +
            '                Interceptor.attach(probeAddr, {\n' +
            '                    onLeave: function(retval) {\n' +
            '                        dumpHex(probe.label, probeAddr, probe.size);\n' +
            '                    }\n' +
            '                });\n' +
            '            })(p, addr);\n' +
            '            console.log("  [+] " + p.label + " @ " + addr);\n' +
            '        }\n' +
            '    }\n' +
            '}\n\n'
        );
    }

    // ── Crypto hooks ──
    if (cryptos.length > 0) {
        script += '// ═══ Spawn Preset: Crypto Hooks ═══\n';
        for (var j = 0; j < cryptos.length; j++) {
            var ch = cryptos[j];
            script += (
                'var cryptoAddr_' + j + ' = Module.findExportByName("' + libName + '", "' + (ch.name || "") + '");\n' +
                'if (cryptoAddr_' + j + ') {\n' +
                '    Interceptor.attach(cryptoAddr_' + j + ', {\n' +
                '        onEnter: function(args) {\n' +
                '            var dLen = Math.min(32, args[2] ? args[2].toInt32() : 32);\n' +
                '            var ds = "(null)";\n' +
                '            if (args[1] && dLen > 0) {\n' +
                '                try { ds = hexdump(args[1].readByteArray(dLen), {offset:0, length:dLen, header:false}); }\n' +
                '                catch(e) { ds = "(read error)"; }\n' +
                '            }\n' +
                '            console.log("[CRYPTO] ' + (ch.name || "?") + ' ctx=" + args[0] + " data=" + ds + " len=" + (args[2] || 0));\n' +
                '        }\n' +
                '    });\n' +
                '    console.log("[*] Spawn crypto hook: ' + (ch.name || "?") + '");\n' +
                '}\n\n'
            );
        }
    }

    // ── installAllHooks ──
    script += (
        '// ═══ Spawn Preset: Install All Hooks ═══\n' +
        'function installAllHooks() {\n' +
        '    var mod = Process.findModuleByName(targetLib);\n' +
        '    if (!mod) {\n' +
        '        console.log("[!] " + targetLib + " not found when installing hooks");\n' +
        '        return;\n' +
        '    }\n' +
        '    console.log("\\n===========================================");\n' +
        '    console.log(" xcore Spawn Preset Active");\n' +
        '    console.log(" " + targetLib + " base=" + mod.base + " size=" + mod.size);\n' +
        '    console.log("===========================================\\n");\n'
    );
    if (rvas.length > 0) {
        script += '    installRVAHooks(mod);\n';
    }
    script += (
        '}\n\n' +
        '// Start waiting for library\n' +
        'setTimeout(waitForLibrary, 100);\n'
    );

    return script;
}

module.exports = { generate, generateSpawnPreset };
